# ==============================================================================
# Install
# ==============================================================================

# Copy targets into the dotfile locations their programs read. Neovim and
# lualine are not copied: the repo itself is the Neovim plugin.
#
# Directories that do not exist are skipped rather than created, so running
# `--install` on a machine without (say) Alacritty doesn't litter $HOME.

HOME = Path.home()
INSTALL_TARGETS = {
    "extras/tmux/myeyes.conf": HOME / ".config/tmux/myeyes.conf",
    "extras/fish/myeyes.theme": HOME / ".config/fish/themes/myeyes.theme",
    "extras/fzf/myeyes.opts": HOME / ".config/fzf/myeyes.opts",
    "extras/codex/myeyes.tmTheme": HOME / ".codex/themes/myeyes.tmTheme",
    "extras/claude/myeyes.json": HOME / ".claude/themes/myeyes.json",
    "extras/alacritty/myeyes.toml": HOME / ".config/alacritty/myeyes.toml",
}

# Created on demand because their parent program directory is known to exist
# whenever the program is installed.
CREATE_PARENTS = {".config/tmux", ".config/fzf", ".config/fish/themes", ".codex/themes", ".claude/themes"}

WINDOWS_TERMINAL_GLOB = (
    "/mnt/c/Users/*/AppData/Local/Packages/"
    "Microsoft.WindowsTerminal_*/LocalState/settings.json"
)


def install(theme: Theme):
    for src, dest in INSTALL_TARGETS.items():
        rel_parent = str(dest.parent.relative_to(HOME))
        program_dir_exists = dest.parent.exists() or (
            rel_parent in CREATE_PARENTS and dest.parent.parent.exists()
        )
        if not program_dir_exists:
            print(f"skip    {dest} (no {dest.parent})")
            continue
        dest.parent.mkdir(exist_ok=True)
        shutil.copyfile(REPO / src, dest)
        print(f"install {dest}")

    # Windows Terminal: replace (or add) only the `myeyes` scheme entry, keeping
    # the rest of settings.json intact. Selecting the scheme is left to the
    # user's profile settings, so reinstalling after a tweak never overrides
    # deliberate per-profile choices.
    import glob

    user = Path(HOME).name
    for path in map(Path, glob.glob(WINDOWS_TERMINAL_GLOB)):
        if path.parts[4] != user:  # /mnt/c/Users/<user>/...
            continue
        raw = path.read_text(encoding="utf-8-sig")
        try:
            settings = json.loads(raw)
        except json.JSONDecodeError:
            # settings.json may contain comments (JSONC); rather than risk a
            # lossy rewrite, leave it to be edited by hand.
            print(f"skip    {path} (not strict JSON; add extras/windows-terminal/myeyes.json by hand)")
            continue
        scheme = windows_terminal_scheme(theme)
        if scheme in settings.get("schemes", []):
            print(f"same    {path} (scheme 'myeyes' up to date)")
            continue
        # Back up once, before the first ever myeyes edit, and never overwrite
        # it: a per-run backup would replace the original after a second tweak.
        backup = path.with_name("settings.json.pre-myeyes.bak")
        if not backup.exists():
            shutil.copyfile(path, backup)
        schemes = [s for s in settings.get("schemes", []) if s.get("name") != "myeyes"]
        schemes.append(scheme)
        settings["schemes"] = schemes
        path.write_text(json.dumps(settings, indent=4, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"install {path} (scheme 'myeyes'; original kept at {backup.name})")


# ==============================================================================
# Entry point
# ==============================================================================


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check", action="store_true", help="fail if generated files are stale")
    p.add_argument("--install", action="store_true", help="copy extras into dotfile locations")
    args = p.parse_args()

    theme = load_theme()
    outputs = [build(theme) for build in BUILDERS]

    if args.check:
        stale = [o.path for o in outputs if not (REPO / o.path).exists()
                 or (REPO / o.path).read_text() != o.content]
        for path in stale:
            print(f"stale   {path}")
        sys.exit(1 if stale else 0)

    for o in outputs:
        dest = REPO / o.path
        dest.parent.mkdir(parents=True, exist_ok=True)
        changed = not dest.exists() or dest.read_text() != o.content
        dest.write_text(o.content)
        print(f"{'wrote' if changed else 'same '}   {o.path}")

    if args.install:
        install(theme)


if __name__ == "__main__":
    main()

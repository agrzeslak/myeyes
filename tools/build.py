# Codex highlights code with syntect, which consumes TextMate themes. TextMate
# scopes are coarser than tree-sitter captures; each rule maps the closest
# scope family onto a role. The same file works for bat and Sublime Text.
#
# TODO: Sublime's Rust grammar scopes primitive types (`u32`, `str`) as
# `storage.type`, the same as `let`, so in Codex/bat they take the storage
# (keyword) colour rather than the type colour. No scope separates them.

TMTHEME_RULES: list[tuple[str, str, str, str]] = [
    # (name, scope selector, role, font style)
    ("Comment", "comment, punctuation.definition.comment", "syntax.comment", ""),
    ("String", "string, punctuation.definition.string", "syntax.string", ""),
    ("Escape", "constant.character.escape, constant.other.placeholder", "syntax.escape", ""),
    ("Number", "constant.numeric", "syntax.number", ""),
    ("Constant", "constant.language, constant.other, support.constant", "syntax.constant", ""),
    ("Keyword", "keyword, keyword.control, keyword.other", "syntax.keyword", ""),
    ("Storage", "storage, storage.type, storage.modifier", "syntax.storage", ""),
    ("Operator", "keyword.operator", "syntax.operator", ""),
    ("Function", "entity.name.function, support.function, meta.function-call", "syntax.function", ""),
    ("Macro", "entity.name.function.macro, support.macro, meta.macro", "syntax.macro", ""),
    ("Type", "entity.name.type, entity.name.class, entity.name.struct, entity.name.enum, support.type, support.class", "syntax.type", ""),
    ("Lifetime", "storage.modifier.lifetime, entity.name.lifetime", "syntax.lifetime", ""),
    ("Attribute", "meta.annotation, meta.attribute, entity.other.attribute-name", "syntax.attribute", ""),
    ("Module", "entity.name.namespace, entity.name.module", "syntax.module", ""),
    ("Variable", "variable, variable.parameter", "syntax.variable", ""),
    ("Punctuation", "punctuation", "syntax.punctuation", ""),
    ("Tag", "entity.name.tag", "syntax.keyword", ""),
    ("Heading", "markup.heading, entity.name.section", "ui.fg_strong", "bold"),
    ("Bold", "markup.bold", "ui.fg_strong", "bold"),
    ("Italic", "markup.italic", "ui.fg", "italic"),
    ("Link", "markup.underline.link", "ui.link", "underline"),
    ("Raw", "markup.raw", "syntax.string", ""),
    ("Inserted", "markup.inserted", "diagnostic.diff_add", ""),
    ("Deleted", "markup.deleted", "diagnostic.diff_delete", ""),
    ("Changed", "markup.changed", "diagnostic.diff_change", ""),
    ("Invalid", "invalid", "diagnostic.error", ""),
]


def _plist_dict(entries: dict[str, str], indent: str) -> list[str]:
    out = [f"{indent}<dict>"]
    for k, v in entries.items():
        out.append(f"{indent}\t<key>{xml_escape(k)}</key>")
        out.append(f"{indent}\t<string>{xml_escape(v)}</string>")
    out.append(f"{indent}</dict>")
    return out


def build_tmtheme(theme: Theme) -> Output:
    settings = {
        "background": hx(theme, "ui.bg"),
        "foreground": hx(theme, "ui.fg"),
        "caret": hx(theme, "ui.cursor"),
        "selection": hx(theme, "ui.selection"),
        "lineHighlight": hx(theme, "ui.cursorline"),
        "invisibles": hx(theme, "ui.fg_subtle"),
        "gutterForeground": hx(theme, "ui.line_number"),
    }
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" '
        '"http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
        f"<!-- {HEADER} -->",
        '<plist version="1.0">',
        "<dict>",
        "\t<key>name</key>",
        "\t<string>myeyes</string>",
        "\t<key>settings</key>",
        "\t<array>",
        "\t\t<dict>",
        "\t\t\t<key>settings</key>",
        *_plist_dict(settings, "\t\t\t"),
        "\t\t</dict>",
    ]
    for name, scope, role, style in TMTHEME_RULES:
        rule = {"foreground": hx(theme, role)}
        if style:
            rule["fontStyle"] = style
        lines += [
            "\t\t<dict>",
            "\t\t\t<key>name</key>",
            f"\t\t\t<string>{xml_escape(name)}</string>",
            "\t\t\t<key>scope</key>",
            f"\t\t\t<string>{xml_escape(scope)}</string>",
            "\t\t\t<key>settings</key>",
            *_plist_dict(rule, "\t\t\t"),
            "\t\t</dict>",
        ]
    lines += ["\t</array>", "</dict>", "</plist>"]
    return Output("extras/codex/myeyes.tmTheme", "\n".join(lines) + "\n")



_NVIM_COLOR_KEYS = ("fg", "bg", "sp")


def _lua_value(v) -> str:
    if v is True:
        return "true"
    if v is False:
        return "false"
    return json.dumps(v)  # strings: JSON escaping is valid Lua for our values


def _nvim_spec(theme: Theme, spec: dict) -> str:
    parts = []
    for key, value in spec.items():
        if key in _NVIM_COLOR_KEYS:
            value = hx(theme, value)
        parts.append(f"{key} = {_lua_value(value)}")
    return "{ " + ", ".join(parts) + " }"


def build_nvim(theme: Theme) -> Output:
    lines = [
        f"-- {HEADER}",
        "-- Source: https://github.com/agrzeslak/myeyes",
        "",
        'vim.cmd("highlight clear")',
        'if vim.fn.exists("syntax_on") == 1 then',
        '\tvim.cmd("syntax reset")',
        "end",
        'vim.o.background = "light"',
        'vim.g.colors_name = "myeyes"',
        "",
        "local hl = vim.api.nvim_set_hl",
        "",
    ]
    for group, spec in NVIM_GROUPS.items():
        lines.append(f'hl(0, "{group}", {_nvim_spec(theme, spec)})')

    # `:terminal` buffers use these, mirroring the terminal emulator schemes.
    lines.append("")
    for i, name in enumerate(ANSI_ORDER):
        lines.append(f'vim.g.terminal_color_{i} = "{hx(theme, "ansi." + name)}"')
    return Output("colors/myeyes.lua", "\n".join(lines) + "\n")



def hx(theme: Theme, role: str) -> str:
    """Resolve a role (`"ui.fg"`) to hex. `"palette.<name>"` reaches a palette
    entry directly, for the rare program-specific colour no role describes
    (e.g. Claude's brand accent and its shimmer)."""
    if role.startswith("palette."):
        return theme.palette[role.removeprefix("palette.")].hex
    return theme.role(role).hex



# Terminal emulators
# ==============================================================================

ANSI_ORDER = [
    "black", "red", "green", "yellow", "blue", "magenta", "cyan", "white",
    "bright_black", "bright_red", "bright_green", "bright_yellow",
    "bright_blue", "bright_magenta", "bright_cyan", "bright_white",
]  # fmt: skip


def windows_terminal_scheme(theme: Theme) -> dict[str, str]:
    # Windows Terminal calls magenta "purple" and uses camelCase brights.
    def wt_name(ansi: str) -> str:
        bright, _, base = ansi.rpartition("_")
        base = "purple" if base == "magenta" else base
        return f"bright{base.capitalize()}" if bright else base

    scheme = {
        "name": "myeyes",
        "background": hx(theme, "ui.bg"),
        "foreground": hx(theme, "ui.fg"),
        "cursorColor": hx(theme, "ui.cursor"),
        "selectionBackground": hx(theme, "ui.selection"),
    }
    scheme |= {wt_name(n): hx(theme, f"ansi.{n}") for n in ANSI_ORDER}
    return scheme


def build_windows_terminal(theme: Theme) -> Output:
    return Output(
        "extras/windows-terminal/myeyes.json",
        json.dumps(windows_terminal_scheme(theme), indent=4) + "\n",
    )


def build_alacritty(theme: Theme) -> Output:
    c = lambda role: hx(theme, role)  # noqa: E731
    lines = [
        f"# {HEADER}",
        '# Use with: general.import = ["~/.config/alacritty/myeyes.toml"]',
        "",
        "[colors.primary]",
        f'background = "{c("ui.bg")}"',
        f'foreground = "{c("ui.fg")}"',
        # Faint text: Alacritty's default darkens colours, which on a light
        # background makes faint text indistinguishable from normal text.
        f'dim_foreground = "{c("ui.fg_muted")}"',
        "",
        "[colors.cursor]",
        f'cursor = "{c("ui.cursor")}"',
        f'text = "{c("ui.cursor_text")}"',
        "",
        "[colors.selection]",
        f'background = "{c("ui.selection")}"',
        f'text = "{c("ui.selection_fg")}"',
        "",
        "[colors.search.matches]",
        f'background = "{c("ui.search")}"',
        f'foreground = "{c("ui.fg")}"',
        "",
        "[colors.search.focused_match]",
        f'background = "{c("ui.search_current")}"',
        f'foreground = "{c("ui.fg_strong")}"',
    ]
    # Dim palette: on a light background "fainter" means lighter, which is
    # what the bright variants already are.
    for section, prefix in (("normal", ""), ("bright", "bright_"), ("dim", "bright_")):
        lines += ["", f"[colors.{section}]"]
        for name in ANSI_ORDER[:8]:
            lines.append(f'{name} = "{c(f"ansi.{prefix}{name}")}"')
    return Output("extras/alacritty/myeyes.toml", "\n".join(lines) + "\n")



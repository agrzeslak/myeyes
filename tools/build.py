# Mode colours follow common convention (insert green, visual purple-ish,
# replace red) using myeyes accents. Section `a` is the mode pill, `b` a
# slightly raised surface, `c` the bar itself.
LUALINE_MODES = {
    "normal": "syntax.function",  # blue
    "insert": "diagnostic.ok",  # green
    "visual": "syntax.keyword",  # magenta
    "replace": "diagnostic.error",  # red
    "command": "diagnostic.warning",  # orange
    "terminal": "syntax.string",  # cyan
}


def build_lualine(theme: Theme) -> Output:
    b_bg, b_fg = hx(theme, "ui.selection"), hx(theme, "ui.fg_strong")
    c_bg, c_fg = hx(theme, "ui.statusline"), hx(theme, "ui.fg")
    pill_fg = hx(theme, "ui.cursor_text")
    lines = [f"-- {HEADER}", "", "return {"]
    for mode, role in LUALINE_MODES.items():
        lines += [
            f"\t{mode} = {{",
            f'\t\ta = {{ fg = "{pill_fg}", bg = "{hx(theme, role)}", gui = "bold" }},',
            f'\t\tb = {{ fg = "{b_fg}", bg = "{b_bg}" }},',
            f'\t\tc = {{ fg = "{c_fg}", bg = "{c_bg}" }},',
            "\t},",
        ]
    lines += [
        "\tinactive = {",
        f'\t\ta = {{ fg = "{hx(theme, "ui.fg_muted")}", bg = "{c_bg}", gui = "bold" }},',
        f'\t\tb = {{ fg = "{hx(theme, "ui.fg_muted")}", bg = "{c_bg}" }},',
        f'\t\tc = {{ fg = "{hx(theme, "ui.fg_muted")}", bg = "{c_bg}" }},',
        "\t},",
        "}",
    ]
    return Output("lua/lualine/themes/myeyes.lua", "\n".join(lines) + "\n")


